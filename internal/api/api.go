var (
	kindIDRe     = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,31}$`)
	agentIDRe    = regexp.MustCompile(`^[a-z0-9][a-z0-9_:-]{0,47}$`)
	contextKeyRe = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,63}$`)
)

// ValidKindID checks user-chosen kind ids (CLI `kind add`, POST /kinds):
// lowercase slug, max 32 chars.
func ValidKindID(s string) bool {
	return kindIDRe.MatchString(s)
}

// ValidAgentID checks agent identity names as generated by the server
// ("kind:hostname:dir" slug parts joined by ":", max 48 chars).
func ValidAgentID(s string) bool {
	return agentIDRe.MatchString(s)
}

type ctxKeyT int

const (
	requestIDKey ctxKeyT = iota
	identityKey
)

// adminAgentID is the panel human's identity, the one row the admin token
// posts as (and the creator of panel-made sessions). Admin-token removals are
// attributed to it in the session notice.
const adminAgentID = "admin"

type Identity struct {
	Agent *store.Agent
	Kind  *store.Kind // kind token: only authorizes registration
	Admin bool
}

